using System.ComponentModel.DataAnnotations;
using System.ComponentModel.DataAnnotations.Schema;

namespace KnowledgeVault.Api.Models;

public class Node
{
    [Key]
    public Guid Id { get; set; } = Guid.NewGuid();

    public Guid? ParentId { get; set; }

    [ForeignKey("ParentId")]
    public Node? Parent { get; set; }

    public ICollection<Node> Children { get; set; } = new List<Node>();

    [Required]
    [MaxLength(500)]
    public string Name { get; set; } = string.Empty;

    public NodeType NodeType { get; set; }

    public Priority? Priority { get; set; }

    public int SortOrder { get; set; }

    /// <summary>
    /// Rich HTML content generated by CKEditor
    /// </summary>
    public string? Content { get; set; }

    /// <summary>
    /// Comma-separated tags (e.g., "Angular,DI,Services")
    /// </summary>
    public string? Tags { get; set; }

    public bool IsFavorite { get; set; }

    public DateTime CreatedOn { get; set; } = DateTime.UtcNow;

    public DateTime UpdatedOn { get; set; } = DateTime.UtcNow;

    // Navigation properties
    public ICollection<NodeImage> Images { get; set; } = new List<NodeImage>();
    public ICollection<NodeOcrImport> OcrImports { get; set; } = new List<NodeOcrImport>();
}
